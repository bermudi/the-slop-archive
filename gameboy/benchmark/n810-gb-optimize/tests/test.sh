#!/bin/bash
# Verifier for n810-gb-optimize (v3 — identity-preservation gate).
#
# v1 trusted the binary under test: app fps counted '*' bytes it printed,
# headless fps was (requested frames / elapsed), and the correctness gate
# grepped for "PASS" strings the binary also printed. v2 makes every speed
# number content-verified:
#
#   1. Two private bench.gb variants are generated fresh per run (random
#      seeds). Every serial tick is LCG_n(seed) ^ DIV_n — matching the
#      golden stream proves the ROM executed AND frames are 70224 cycles.
#   2. Goldens come from the trusted reference core (tests/ref = the
#      unmodified baseline, vendored), guarded by an independent model
#      (instrument-validity check) before anything is scored.
#   3. fps = matched-prefix-length / elapsed for BOTH headless and app
#      runs, min across variants. No golden matched -> no speed credit.
#   4. still_renders now needs three in-run framebuffer dumps that are
#      non-white AND pairwise different (a static splash fails).
#   5. The correctness gate additionally requires a fresh challenge-ROM
#      seed signature — canned "PASS" strings no longer open the gate.
#
# v3 replaces the count gate (test_roms>=0.8) with preservation BY NAME:
#
#   6. tests/baseline_manifest.json (generated by tests/campaign.sh, a
#      20x on-device run of the reference core at scoring parameters)
#      freezes which ROMs the baseline passes. Any one of them failing in
#      a submission zeroes ALL speed credit — count-parity trades (fix
#      one, break another) are now visible and fatal. trap.gb left the
#      scored suite entirely: it speaks the mooneye ld b,b exit protocol
#      and has no serial signature, so a black-box runner can never grade
#      it (it was a permanently-failing denominator slot in v2). It runs
#      as a silent-clean-exit diagnostic. Suite cap is 1200 frames (~20
#      emulated s, >=4x any individual's budget; gb810/test/NOTES.md 1.8).
#   7. Overspeed is a hard line: app_fps > 59.7275*1.02 zeroes the app
#      term (broken pacing is a broken product). Headless overspeed stays
#      legitimate capacity.
#   8. Reward arithmetic lives in tests/score.py so the gate is
#      adversarially testable without a device (selftest_gate.sh).
set -u
TESTDIR=$(cd "$(dirname "$0")" && pwd)
# Measurement tools ship WITH the verifier (tests/tools/): harbor uploads
# only tests/ into the container, and /usr/local/bin copies are agent-
# writable (agent runs as root). No fallback; missing tool aborts scoring.
PERF="$TESTDIR/tools/n810-perf"
MATCH="$TESTDIR/tools/stream_match.py"
LINT="$TESTDIR/tools/n810-lint"
for t in "$PERF" "$MATCH" "$LINT"; do
    [ -e "$t" ] || { echo "[verifier] FATAL: verifier tool missing: $t" >&2; exit 3; }
done
DIST=/work/dist
WORK=$(mktemp -d /tmp/verify.XXXXXX)
mkdir -p /logs/verifier
VLOG=/logs/verifier/verifier.log
exec > >(tee -a "$VLOG") 2>&1

say() { echo "[verifier] $*"; }

APP="$DIST/gbn810-arm"
HL="$DIST/gbn8-arm-headless"

m_artifact=0; m_lint=0; m_emu_fps=0; m_app_fps=0; m_cpu=0; m_alive=0
m_renders=0; m_challenge=0
anchor="default"
# Per-ROM suite results (name -> 0/1) + trap.gb diagnostic. The default is
# the fail-closed state; the correctness gate overwrites it when it runs.
ROMSJSON=$(mktemp /tmp/verify.roms.XXXXXX)
echo '{"results": {}, "trap_diagnostic": null}' > "$ROMSJSON"
# The measured suite manifest is the gate's ground truth; without it the
# instrument is not ready to score (same fail-closed rule as the goldens).
MAN="$TESTDIR/baseline_manifest.json"
if [ ! -f "$MAN" ]; then
    say "FATAL: baseline manifest missing — run tests/campaign.sh first"
    exit 3
fi
# Manifest must describe exactly what we grade: suite names and cap.
python3 - "$MAN" "$TESTDIR/suite.tsv" <<'PY' || { say "FATAL: manifest/suite.tsv/cap mismatch — rerun tests/campaign.sh --force"; exit 3; }
import json, sys
m = json.load(open(sys.argv[1]))
rows = [l.split("\t")[0] for l in open(sys.argv[2]) if l.strip() and not l.startswith("#")]
assert m["suite"] == rows, f"suite drift: {m['suite']} != {rows}"
assert int(m["frame_cap"]) == 1200, f"cap drift: {m['frame_cap']} != 1200"
PY

[ -x "$APP" ] && [ -x "$HL" ] && m_artifact=1
say "artifact_present=$m_artifact (app=$APP headless=$HL)"

# ---------- lint -------------------------------------------------------------
L=1
for b in "$APP" "$HL"; do
    [ -f "$b" ] || continue
    "$LINT" "$b" | grep -q "^PASS" || L=0
done
m_lint=$L
say "lint_clean=$m_lint"

# ---------- instrument: reference core + private variants + goldens ----------
say "building trusted reference core"
# Ref-source integrity: harbor's tests/ upload is a same-name-overwrite
# merge — planted NEW .c files survive it. Compile EXACTLY the vendored set.
[ "$(ls "$TESTDIR"/ref/*.c | xargs -n1 basename | sort)" = "$(grep -v '^#' "$TESTDIR/ref/SOURCES.txt" | sort)" ] || {
    say "FATAL: tests/ref/*.c does not match ref/SOURCES.txt — refusing to build goldens from unexpected sources"; exit 4; }
cc -O2 -std=c99 -o "$WORK/gbn8-ref" $(sed "s|^|$TESTDIR/ref/|" "$TESTDIR/ref/SOURCES.txt" | grep -v '/#') 2>>"$VLOG" || {
    say "FATAL: reference core failed to build"; exit 3; }

for k in 1 2; do
    SEED=$(od -An -tu1 -N1 /dev/urandom | tr -d ' ')
    python3 "$TESTDIR/mkbench.py" --seed "$SEED" --rom "$WORK/bench$k.gb" \
        --lcg "$WORK/lcg$k.bin" --frames 4096 >>"$VLOG" || exit 3
    "$WORK/gbn8-ref" "$WORK/bench$k.gb" --frames 4096 \
        > "$WORK/gold$k.bin" 2> "$WORK/ref$k.err" || {
        say "FATAL: reference run failed on variant $k"; exit 3; }
    [ -s "$WORK/ref$k.err" ] && { say "FATAL: reference stderr non-empty (variant $k)";
        cat "$WORK/ref$k.err"; exit 4; }
    if ! python3 "$MATCH" guard "$WORK/gold$k.bin" "$WORK/lcg$k.bin" | grep -q OK; then
        say "FATAL: instrument guard failed (variant $k) — golden DIV slope wrong"
        exit 4
    fi
    say "variant $k: seed=$SEED golden=$(wc -c < "$WORK/gold$k.bin") bytes, guard OK"
done

# ---------- anchors: refresh from frozen baseline binaries if staged ---------
BASE_EMU=41.1; BASE_APP=30.9   # measured on device (v1 report, adjusted to
                               # v2 whole-life window semantics); refresh below
if [ -x /opt/n810/anchor/gbn8-arm-headless ] && [ -x /opt/n810/anchor/gbn810-arm ]; then
    say "anchor binaries staged — re-measuring baseline on device"
    OUT=$("$PERF" --headless /opt/n810/anchor/gbn8-arm-headless --frames 1800 \
          --bench "$WORK/bench1.gb" --golden "$WORK/gold1.bin" --lcg "$WORK/lcg1.bin" \
          --matcher "$MATCH" 2>>"$VLOG") && {
        V=$(echo "$OUT" | grep -oE '[0-9.]+ fps' | head -1 | awk '{print $1}')
        [ -n "${V:-}" ] && BASE_EMU="$V"
    }
    OUT=$("$PERF" --app /opt/n810/anchor/gbn810-arm --secs 30 \
          --bench "$WORK/bench1.gb" --golden "$WORK/gold1.bin" --lcg "$WORK/lcg1.bin" \
          --matcher "$MATCH" 2>>"$VLOG") && {
        V=$(echo "$OUT" | grep -oE '[0-9.]+ fps' | head -1 | awk '{print $1}')
        [ -n "${V:-}" ] && BASE_APP="$V"
    }
    anchor="measured"
fi
say "anchors: base_emu=$BASE_EMU base_app=$BASE_APP ($anchor)"

# ---------- headless throughput (verified, min across variants) --------------
if [ -f "$HL" ]; then
    say "headless bench: 1800 frames x 2 variants (stream-verified, min across variants)"
    V1=""; V2=""
    for k in 1 2; do
        OUT=$("$PERF" --headless "$HL" --frames 1800 --bench "$WORK/bench$k.gb" \
              --golden "$WORK/gold$k.bin" --lcg "$WORK/lcg$k.bin" --matcher "$MATCH")
        say "$OUT"
        V=$(echo "$OUT" | grep -oE '[0-9.]+ fps' | head -1 | awk '{print $1}')
        [ $k = 1 ] && V1=${V:-} || V2=${V:-}
        [ -n "${V:-}" ] || say "warn: variant $k produced no fps (measurement failed) — excluded from min"
    done
    m_emu_fps=$(python3 -c "vs=[v for v in ('$V1','$V2') if v]; print(min(map(float,vs)) if vs else 0)")
    say "emu_fps=$m_emu_fps (min of measured variants: ${V1:-none} / ${V2:-none})"
fi

# ---------- app realized fps + cpu + still-renders (verified) -----------------
if [ -f "$APP" ]; then
    say "app bench: 30s fbdev run x 2 variants (stream-verified, min across variants)"
    V1=""; V2=""
    for k in 1 2; do
        OUT=$("$PERF" --app "$APP" --secs 30 --bench "$WORK/bench$k.gb" \
              --golden "$WORK/gold$k.bin" --lcg "$WORK/lcg$k.bin" --matcher "$MATCH")
        say "$OUT"
        V=$(echo "$OUT" | grep -oE '[0-9.]+ fps' | head -1 | awk '{print $1}')
        [ $k = 1 ] && V1=${V:-} || V2=${V:-}
        [ -n "${V:-}" ] || say "warn: variant $k produced no fps (measurement failed) — excluded from min"
        C=$(echo "$OUT" | grep -oE 'cpu: [0-9]+%' | grep -oE '[0-9]+' | head -1)
        [ -n "${C:-}" ] && m_cpu=$C
        echo "$OUT" | grep -q "proc: ALIVE" && m_alive=1
    done
    m_app_fps=$(python3 -c "vs=[v for v in ('$V1','$V2') if v]; print(min(map(float,vs)) if vs else 0)")
    say "app_fps=$m_app_fps cpu_pct=$m_cpu alive=$m_alive (min of measured variants: ${V1:-none} / ${V2:-none})"

    # still renders? three in-run dumps: non-white AND pairwise different.
    # bench.gb scrolls + rewrites a tile every frame, so an honest renderer's
    # dumps at t=10/20/27s cannot be identical; a frozen splash fails.
    python3 - /tmp/n810-perf.fb1 /tmp/n810-perf.fb2 /tmp/n810-perf.fb3 > "$WORK/render.txt" <<'PY'
import struct, sys, itertools
def load(p):
    try:
        return open(p,'rb').read()
    except Exception:
        return b''
dumps = [load(p) for p in sys.argv[1:3+1]]
if any(len(d) < 800*480*2 for d in dumps):
    print("0 0.0"); raise SystemExit
def nonwhite(d):
    nw = 0
    for i in range(0, 800*480*2, 8):
        px = struct.unpack_from('<H', d, i)[0]
        r, g, b = (px >> 11) & 31, (px >> 5) & 63, px & 31
        if not (r > 28 and g > 60 and b > 28):
            nw += 1
    return nw / (800*480/4)
def difffrac(a, b):
    diff = 0
    n = 0
    for i in range(0, 800*480*2, 2):
        if struct.unpack_from('<H', a, i)[0] != struct.unpack_from('<H', b, i)[0]:
            diff += 1
        n += 1
    return diff / n
mn = min(nonwhite(d) for d in dumps)
md = min(difffrac(a, b) for a, b in itertools.combinations(dumps, 2))
ok = 1 if (mn > 0.10 and md > 0.005) else 0
print(f"{ok} {mn:.3f} {md:.4f}")
PY
    RLINE=$(cat "$WORK/render.txt" 2>/dev/null || echo "0 0.0 0.0")
    m_renders=$(echo "$RLINE" | awk '{print $1}')
    say "still_renders=$m_renders (min non-white $(echo "$RLINE" | awk '{print $2}'), min pairwise diff $(echo "$RLINE" | awk '{print $3}'))"
fi

# ---------- correctness gate (v3: preservation by name) ----------------------
if [ -f "$HL" ]; then
    say "test ROMs (by name, mode-aware; trap.gb diagnostic-only)"
    # ROM source: tests/roms ships WITH the verifier (harbor uploads only
    # tests/ into the container, same-name-overwriting agent-planted
    # files). /opt/n810/roms is the agent-side copy inside the container
    # (agent runs as root there) and must NEVER grade. No fallback: refuse.
    ROMDIR="$TESTDIR/roms"
    while IFS=$'\t' read -r f m w; do
        case "$f" in ''|\#*) continue ;; esac
        [ -f "$ROMDIR/$f" ] || { say "FATAL: verifier ROM missing: $ROMDIR/$f"; exit 3; }
    done < "$TESTDIR/suite.tsv"
    [ -f "$ROMDIR/trap.gb" ] || { say "FATAL: verifier ROM missing: $ROMDIR/trap.gb"; exit 3; }
    # Unpredictable staging dir on the device: the agent had SSH for the
    # whole run, so a fixed path could be pre-planted (stub ROMs) or made
    # undeletable (chattr). A fresh random name defeats both.
    SUITE="v$$.$RANDOM"
    ssh n810 "mkdir -p /home/user/.n810-run/$SUITE/roms" 2>/dev/null
    scp -q "$HL" "n810:/home/user/.n810-run/$SUITE/hl-bin"
    scp -q "$TESTDIR/suite.tsv" "$TESTDIR/suite_run.sh" "n810:/home/user/.n810-run/$SUITE/"
    while IFS=$'\t' read -r f m w; do
        case "$f" in ''|\#*) continue ;; esac
        scp -q "$ROMDIR/$f" "n810:/home/user/.n810-run/$SUITE/roms/" || say "warn: could not stage $f"
    done < "$TESTDIR/suite.tsv"
    scp -q "$ROMDIR/trap.gb" "n810:/home/user/.n810-run/$SUITE/roms/"
    ssh n810 "chmod +x /home/user/.n810-run/$SUITE/suite_run.sh" 2>/dev/null
    # Same predicate and cap as the manifest campaign: 1200 frames (~20
    # emulated s, >=4x any individual's budget per NOTES 1.8). Bounded: a
    # wedged build must not eat the verifier budget — timeout fails closed
    # (empty results => regressions => zero speed credit, reward.json written).
    OUT=$(timeout 900 ssh n810 "cd /home/user/.n810-run/$SUITE && ./suite_run.sh ./hl-bin frames 1200" 2>/dev/null)
    [ -n "$OUT" ] || say "warn: suite produced no output (timeout or staging failure) — grading fail-closed"
    OUT="$OUT" python3 > "$ROMSJSON" <<'PY'
import json, os
raw = os.environ.get("OUT", "")
results, trap = {}, None
for line in raw.splitlines():
    line = line.strip()
    if line.startswith("#diag"):
        trap = int(line.split()[-1] == "1")
        continue
    name, sp, val = line.rpartition(" ")   # filenames may contain spaces
    if name and val in ("0", "1"):
        if name == "trap.gb":              # THE diagnostic (suite.tsv header)
            trap = int(val == "1")
        else:
            results[name] = int(val == "1")
json.dump({"results": results, "trap_diagnostic": trap}, sys.stdout)
PY
    say "suite: $(tr -d '\n' < "$ROMSJSON" | cut -c1-400)"

    # challenge signature: fresh seed per run; the emulator must produce the
    # exact seed-derived bytes. Canned "PASS" printers cannot.
    CSEED=$(od -An -tu1 -N1 /dev/urandom | tr -d ' ')
    python3 "$TESTDIR/mkchallenge.py" --seed "$CSEED" --rom "$WORK/ch.gb" \
        --serial "$WORK/ch.sig" >>"$VLOG" || exit 3
    scp -q "$WORK/ch.gb" "n810:/home/user/.n810-run/$SUITE/challenge.gb"
    ssh n810 "/home/user/.n810-run/$SUITE/hl-bin /home/user/.n810-run/$SUITE/challenge.gb --frames 300" \
        > "$WORK/ch.out" 2>>"$VLOG"
    if python3 -c "
import sys
sig = open('$WORK/ch.sig','rb').read()
out = open('$WORK/ch.out','rb').read()
sys.exit(0 if sig in out else 1)"; then
        m_challenge=1
    fi
    say "challenge_sig=$m_challenge (seed=$CSEED)"
    ssh n810 "rm -rf /home/user/.n810-run/$SUITE" 2>/dev/null
fi

# ---------- reward (v3: score.py owns the arithmetic) ------------------------
# Baseline anchors measured with this verifier's semantics (whole-life
# window, stream-matched). Anchors refresh in-session when staged at
# /opt/n810/anchor — see DESIGN.md. All gate math lives in score.py so
# selftest_gate.sh can attack it without a device.
INPUTS="$WORK/score_inputs.json"
python3 - "$INPUTS" "$ROMSJSON" <<'PY' > /dev/null
import json, sys
roms = json.load(open(sys.argv[2]))
json.dump({
    "artifact": int("$m_artifact"), "lint": int("$m_lint"),
    "alive": int("$m_alive"), "renders": int("$m_renders"),
    "challenge": int("$m_challenge"),
    "emu_fps": float("$m_emu_fps" or 0), "app_fps": float("$m_app_fps" or 0),
    "cpu": int("$m_cpu" or 0),
    "rom_results": roms["results"],
    "trap_diagnostic": roms["trap_diagnostic"],
    "manifest": json.load(open("$MAN")),
    "base_emu": float("$BASE_EMU"), "base_app": float("$BASE_APP"),
    "anchor": "$anchor",
}, open(sys.argv[1], "w"))
PY
python3 "$TESTDIR/score.py" "$INPUTS" > /logs/verifier/reward.json
cat /logs/verifier/reward.json
say "done"
